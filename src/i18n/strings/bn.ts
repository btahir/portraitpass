/**
 * Genitive of a document name: "পাসপোর্ট" gives "পাসপোর্টের", "ভিসা" gives "ভিসার", and a name that
 * ends in a Latin letter, digit or bracket ("OCI", "(DS-160)") takes a hyphenated "-এর".
 */
const genitive = (name: string): string => {
  const last = name.slice(-1);
  if (/[ক-হ়ৎড়-য়]/.test(last)) return `${name}ের`; // consonant, nukta, khanda-ta
  if (/[ািীুূেো]/.test(last)) return `${name}র`; // vowel signs
  return `${name}-এর`;
};

