// ------------------------------------------------------------ social cards
const DOC_PATH_ID = new Map(DOCUMENTS.map((d) => [`/${d.id}-photo/`, d.id]));
/**
 * The card for a page: one per document and per size or guide page (generated by the prerender
 * script from scripts/lib/og-cards.ts), shared by every language. Other pages use the home card.
 */
function ogImageFor(path: string): string {
  const en = toEnglishPath(path);
  if (!isTranslatable(en)) return absolute("/og.png");
  return absolute(`/og/${DOC_PATH_ID.get(en) ?? en.replace(/\//g, "")}.png`);
}
const withCommon = (path: string, meta: Omit<RouteMeta, "ogImage" | "ogImageAlt"> & { ogImageAlt?: string }): RouteMeta => ({
  ...meta,
  ogImage: ogImageFor(path),
  ogImageAlt: meta.ogImageAlt ?? meta.title,
});

