export function normalizePath(pathname: string): string {
  let p = pathname.split(/[?#]/)[0] || "/";
  if (!p.startsWith("/")) p = `/${p}`;
  return p === "/" ? "/" : `${p.replace(/\/+$/, "")}/`;
}

const absolute = (path: string) => `${SITE_URL}${path}`;
