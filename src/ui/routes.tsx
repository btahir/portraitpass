export interface HreflangLink {
  hreflang: string;
  /** Absolute URL. */
  href: string;
}
export interface RouteMeta {
  title: string;
  description: string;
  canonical: string;
  jsonLd?: object[];
  /** Keep the page out of search results (thin or utility pages). It is also left out of the sitemap. */
  noindex?: boolean;
  /** YYYY-MM-DD: when the page's content last changed (the dataset check date, or the legal update). */
  lastmod?: string;
  /** Absolute URL of the social card, and its alt text. */
  ogImage: string;
  ogImageAlt: string;
  /** <html lang>, and og:locale. */
  lang: string;
  dir: "ltr" | "rtl";
  ogLocale: string;
  /** hreflang alternates (including x-default) for pages that exist in more than one language. */
  alternates: HreflangLink[];
}
export interface StaticRoute extends RouteMeta {
  element: ReactElement;
}

