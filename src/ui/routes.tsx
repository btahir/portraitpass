/** The page itself: language, last check date and, where the numbers come from, its sources. */
function webPageLd(opts: {
  path: string;
  title: string;
  description: string;
  lang: string;
  lastmod?: string;
  sources?: { title: string; url: string }[];
}) {
  return {
    "@context": "https://schema.org",
    "@type": "WebPage",
    "@id": `${absolute(opts.path)}#webpage`,
    url: absolute(opts.path),
    name: opts.title,
    description: opts.description,
    inLanguage: opts.lang,
    isPartOf: { "@id": SITE_ID },
    publisher: { "@id": ORG_ID },
    primaryImageOfPage: { "@type": "ImageObject", url: ogImageFor(opts.path), width: 1200, height: 630 },
    ...(opts.lastmod ? { dateModified: opts.lastmod, lastReviewed: opts.lastmod } : {}),
    ...(opts.sources?.length
      ? { isBasedOn: opts.sources.map((s) => ({ "@type": "CreativeWork", name: s.title, url: s.url })) }
      : {}),
  };
}
/** The dataset behind the pages, for Google Dataset Search. The JSON file is written by scripts/prerender.ts. */
function datasetLd() {
  const countries = [...new Set(DOCUMENTS.map((d) => d.country))].sort();
  const checks = DOCUMENTS.flatMap((d) => d.sources.map((s) => s.checkedAt)).sort();
  const sources = [...new Set(DOCUMENTS.flatMap((d) => d.sources.map((s) => s.url)))].sort();
  return {
    "@context": "https://schema.org",
    "@type": "Dataset",
    "@id": `${SITE_URL}/#dataset`,
    name: "Passport, visa and ID photo requirements",
    description: `Photo size, head and eye position, background and file size rules for ${DOCUMENTS.length} passports, visas and ID documents from ${countries.length} countries and regions. Each entry lists the issuing authority's own source page and the date it was last checked. The entries are a well-sourced starting point: re-check the source page before relying on a number.`,
    url: absolute("/documents/"),
    keywords: ["passport photo size", "visa photo requirements", "ID photo dimensions", "photo file size limit", "head height", "biometric photo"],
    license: "https://opensource.org/license/mit",
    isAccessibleForFree: true,
    inLanguage: "en",
    creator: { "@id": ORG_ID },
    publisher: { "@id": ORG_ID },
    dateModified: checks[checks.length - 1],
    temporalCoverage: `${checks[0]}/${checks[checks.length - 1]}`,
    spatialCoverage: countries.map((c) => ({ "@type": "Place", name: c })),
    variableMeasured: [
      "Printed photo width and height (mm)",
      "Head height range (mm)",
      "Eye line position (mm)",
      "Background colour",
      "Upload width and height (px)",
      "File size limit (KB)",
      "Accepted file formats",
    ],
    isBasedOn: sources,
    distribution: [
      { "@type": "DataDownload", encodingFormat: "application/json", contentUrl: absolute("/data/documents.json") },
    ],
    sameAs: `${REPO_URL}/tree/main/src/core/data`,
  };
}

function faqLd(faq: Faq[]) {
  return {
    "@context": "https://schema.org",
    "@type": "FAQPage",
    mainEntity: faq.map((f) => ({
      "@type": "Question",
      name: f.q,
      acceptedAnswer: { "@type": "Answer", text: f.a },
    })),
  };
}
function crumbLd(items: { name: string; path?: string }[], L: Locale) {
  return {
    "@context": "https://schema.org",
    "@type": "BreadcrumbList",
    itemListElement: [{ name: strings(L).shell.home, path: "/" }, ...items].map((it, i) => ({
      "@type": "ListItem",
      position: i + 1,
      name: it.name,
      ...(it.path ? { item: absolute(it.path) } : {}),
    })),
  };
}

/** Language, direction and hreflang alternates for a page at `path`. */
function localeMeta(path: string) {
  const L = localeOf(path);
  const alts = alternatesFor(path);
  const alternates: HreflangLink[] = alts.length
    ? [
        ...alts.map((a) => ({ hreflang: a.hreflang, href: absolute(a.path) })),
        {
          hreflang: "x-default",
          href: absolute(alts.find((a) => a.locale === DEFAULT_LOCALE)!.path),
        },
      ]
    : [];
  return {
    lang: LOCALES[L].hreflang,
    dir: LOCALES[L].dir,
    ogLocale: LOCALES[L].ogLocale,
    alternates,
  };
}

interface Entry {
  path: string;
  build: () => StaticRoute;
}

const fixed = (
  path: string,
  title: string,
  description: string,
  crumb: string,
  element: () => ReactElement,
  opts: { noindex?: boolean } = {},
): Entry => ({
  path,
  build: () => ({
    ...withCommon(path, {
      title,
      description,
      canonical: absolute(path),
      jsonLd: [crumbLd([{ name: crumb }], DEFAULT_LOCALE)],
      lastmod: LEGAL_UPDATED,
      ...(opts.noindex ? { noindex: true } : {}),
      ...localeMeta(path),
    }),
    element: element(),
  }),
});

function fromDef(def: PageDef, L: Locale): Entry {
  const path = withLocale(def.path, L);
  return {
    path,
    build: () => {
      const meta = localeMeta(path);
      const lastmod = ALL_CHECKED();
      return {
        ...withCommon(path, {
          title: def.title,
          description: def.description,
          canonical: absolute(path),
          lastmod,
          jsonLd: [
            crumbLd([{ name: def.crumb }], L),
            webPageLd({ path, title: def.title, description: def.description, lang: meta.lang, lastmod }),
            ...(def.faq ? [faqLd(def.faq)] : []),
          ],
          ...meta,
        }),
        element: def.element,
      };
    },
  };
}

function fromDocument(doc: DocumentSpec, L: Locale): Entry {
  const path = docPath(doc, L);
  return {
    path,
    build: () => {
      const { title, description } = documentMeta(doc, L);
      const meta = localeMeta(path);
      const lastmod = checkedIso(doc) || undefined;
      return {
        ...withCommon(path, {
          title,
          description,
          canonical: absolute(path),
          lastmod,
          jsonLd: [
            crumbLd(
              [
                { name: strings(L).index.crumb, path: withLocale("/documents/", L) },
                { name: localizeDocument(doc, L).name },
              ],
              L,
            ),
            webPageLd({
              path,
              title,
              description,
              lang: meta.lang,
              lastmod,
              sources: doc.sources.map((x) => ({ title: x.title, url: x.url })),
            }),
            faqLd(documentFaq(doc, L)),
          ],
          ...meta,
        }),
        element: <DocumentPage doc={doc} locale={L} />,
      };
    },
  };
}

function documentsIndex(L: Locale): Entry {
  const path = withLocale("/documents/", L);
  const t = strings(L);
  return {
    path,
    build: () => {
      const meta = localeMeta(path);
      const title = t.meta.indexTitle;
      const description = t.meta.indexDescription(DOCUMENTS.length);
      const lastmod = ALL_CHECKED();
      return {
        ...withCommon(path, {
          title,
          description,
          canonical: absolute(path),
          lastmod,
          jsonLd: [
            crumbLd([{ name: t.index.crumb }], L),
            webPageLd({ path, title, description, lang: meta.lang, lastmod }),
            // The dataset is described once, on the English page (its JSON file is English).
            ...(L === DEFAULT_LOCALE ? [datasetLd()] : []),
          ],
          ...meta,
        }),
        element: <DocumentsIndexPage locale={L} />,
      };
    },
  };
}

/** Documents, size pages and print guide in one locale. */
function localizedEntries(L: Locale): Entry[] {
  const list: Entry[] = [documentsIndex(L), ...sizePages(L).map((d) => fromDef(d, L))];
  const taken = new Set(list.map((e) => e.path));
  for (const doc of DOCUMENTS) {
    const path = docPath(doc, L);
    if (taken.has(path)) continue;
    taken.add(path);
    list.push(fromDocument(doc, L));
  }
  return list;
}

// Translated pages exist only for language packs that are loaded (a page load needs one language;
// the prerender script loads them all), so the table is rebuilt if the set of loaded packs changes.
let cache: Map<string, Entry> | undefined;
let cacheKey = "";
function entries(): Map<string, Entry> {
  const translations = loadedTranslations();
  const key = translations.join();
  if (cache && key === cacheKey) return cache;
  const list: Entry[] = [
    fixed(
      "/about/",
      "About PortraitPass",
      "An independent open-source passport photo tool. Your photos stay on your device. Learn how it works, where the numbers come from and what it cannot promise.",
      "About",
      () => <AboutPage />,
    ),
    fixed(
      "/support/",
      "Support PortraitPass",
      "Tips keep PortraitPass free, private and open source. Optional one-time or monthly tips; they never unlock features or touch your photos.",
      "Support",
      () => <SupportPage />,
      // A short tipping page: nothing to rank for, so it stays out of search results.
      { noindex: true },
    ),
    fixed(
      "/privacy/",
      "Privacy — PortraitPass",
      "Your photo never leaves your device. What the host logs, why there are no cookies or analytics, and what a saved project file contains.",
      "Privacy",
      () => <PrivacyPage />,
    ),
    fixed(
      "/terms/",
      "Terms — PortraitPass",
      "PortraitPass is a free open-source tool provided as is, under the MIT License, with no guarantee that any photo is accepted.",
      "Terms",
      () => <TermsPage />,
    ),
    fixed(
      "/accessibility/",
      "Accessibility — PortraitPass",
      "How PortraitPass works with a keyboard and screen reader, the WCAG 2.2 AA standard we aim for, known limits, and how to report an accessibility barrier.",
      "Accessibility",
      () => <AccessibilityPage />,
    ),
    // English documents index (its title text lives with the other English strings).
    documentsIndex(DEFAULT_LOCALE),
    ...sizePages(DEFAULT_LOCALE).map((d) => fromDef(d, DEFAULT_LOCALE)),
  ];
  const taken = new Set(list.map((e) => e.path));
  // The US and UK passport pages double as the long-standing keyword URLs.
  for (const doc of DOCUMENTS) {
    const path = docPath(doc);
    if (taken.has(path)) continue;
    taken.add(path);
    list.push(fromDocument(doc, DEFAULT_LOCALE));
  }
  for (const L of translations) list.push(...localizedEntries(L));
  cacheKey = key;
  cache = new Map(list.map((e) => [e.path, e]));
  return cache;
}

/** Route for a pathname, or undefined (home, studio, and unknown paths belong to the app). */
export function matchStaticRoute(pathname: string): StaticRoute | undefined {
  return entries().get(normalizePath(pathname))?.build();
}

/** Every path to prerender and list in the sitemap, in a stable order. */
export function staticRoutes(): string[] {
  return ["/", "/studio/", ...entries().keys()];
}

/** Title, description and structured data for any prerendered path (including / and /studio/). */
export function routeMeta(pathname: string): RouteMeta | undefined {
  const path = normalizePath(pathname);
  const base = localeMeta(path);
  if (path === "/")
    return withCommon(path, {
      ...HOME_META,
      ...base,
      canonical: absolute("/"),
      lastmod: ALL_CHECKED(),
      jsonLd: [organizationLd(), websiteLd(), applicationLd()],
    });
  // The studio is the app itself: an empty shell until the script runs, with the same address for
  // every document (?doc=). The document pages and the home page are what should rank, so it is
  // kept out of the index (links from it are still followed).
  if (path === "/studio/")
    return withCommon(path, { ...STUDIO_META, ...base, canonical: absolute("/studio/"), noindex: true });
  const route = matchStaticRoute(path);
  if (!route) return undefined;
  const { element: _element, ...meta } = route;
  return meta;
}
